def run_demo(output: Path) -> dict[str, Any]:
    """Create a complete example workspace and return its evidence."""
    output = output.expanduser().resolve()
    if output.exists() and any(output.iterdir()):
        raise FileExistsError(f"Demo output is not empty: {output}")
    new_project(
        "Forge Demo",
        "rimworldforge.demo",
        author="RimWorldForge",
        description="Generated by `rwforge demo`.",
        workspace=output,
        versions=["1.6", "1.7"],
    )
    plan_path = output / "plans" / "demo.plan.json"
    write_json(plan_path, PLAN)
    generated = apply_plan(output, plan_path)
    if not generated.get("ok"):
        return {"ok": False, "stage": "generate", "result": generated}

    # Imported here so the core CLI can be inspected without loading Pillow.
    try:
        from .artgen import generate_assets
    except ImportError as exc:
        raise ValueError("Pillow is required for procedural art. Install with: pip install Pillow") from exc

    assets = generate_assets(output, force=True, seed="rwforge-demo")
    validation = validate_workspace(output)
    if not validation["ok"]:
        return {"ok": False, "stage": "validate", "validation": validation, "assets": assets}
    built = build_project(output)
    return {
        "ok": bool(built.get("ok")),
        "workspace": str(output),
        "plan": str(plan_path),
        "assets": assets,
        "validation": {
            "ok": validation["ok"],
            "errors": validation["errors"],
            "warnings": [warning["code"] for warning in validation["warnings"]],
        },
        "archive": built.get("archive"),
        "receipt": built.get("receipt"),
        "note": "Pipeline proof only. Open the PNGs and load the mod in RimWorld before calling it working.",
    }
